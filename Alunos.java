public class Alunos {

    private int id;
    private String nome;
    private String sala;

    public Alunos(int id, String nome, String sala){
        this.id = id;
        this.nome = nome;
        this.sala = sala;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getSala() {
        return sala;
    }

    public void setSala(String sala) {
        this.sala = sala;
    }

    
    
    

}
